#!/usr/bin/env python3
"""Select local SWE-ReBench rows from a Parquet built by Uni-Agent upstream."""

from __future__ import annotations

import argparse
from pathlib import Path

from datasets import load_dataset


def _read_instance_ids(path: Path) -> list[str]:
    instance_ids = [
        line.split("#", 1)[0].strip()
        for line in path.read_text(encoding="utf-8").splitlines()
    ]
    instance_ids = [instance_id for instance_id in instance_ids if instance_id]
    if not instance_ids:
        raise ValueError(f"no instance IDs found in {path}")
    if len(instance_ids) != len(set(instance_ids)):
        raise ValueError(f"duplicate instance IDs found in {path}")
    return instance_ids


def _task_metadata(row: dict) -> dict:
    try:
        metadata = row["extra_info"]["tools_kwargs"]["task"]["metadata"]
    except (KeyError, TypeError) as exc:
        raise ValueError(
            "input Parquet does not use Uni-Agent's SWE-ReBench Task Config schema"
        ) from exc
    if not isinstance(metadata, dict):
        raise ValueError("SWE-ReBench task metadata must be a mapping")
    return metadata


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        required=True,
        help="Parquet generated by Uni-Agent preprocess.",
    )
    parser.add_argument(
        "--instance-ids-file",
        type=Path,
        required=True,
        help="One instance_id per line.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Output Parquet path.",
    )
    args = parser.parse_args()

    for name, path in (
        ("--input", args.input),
        ("--instance-ids-file", args.instance_ids_file),
    ):
        if not path.is_file():
            parser.error(f"{name} does not exist or is not a file: {path}")
    if args.input.resolve() == args.output.resolve():
        parser.error("--output must differ from --input")

    instance_ids = _read_instance_ids(args.instance_ids_file)
    dataset = load_dataset(
        "parquet",
        data_files={"train": str(args.input)},
        split="train",
    )

    positions: dict[str, int] = {}
    requested = set(instance_ids)
    for index, row in enumerate(dataset):
        instance_id = _task_metadata(row).get("instance_id")
        if instance_id in requested:
            if instance_id in positions:
                raise ValueError(
                    f"input Parquet contains duplicate instance_id={instance_id!r}"
                )
            positions[instance_id] = index

    missing = [
        instance_id for instance_id in instance_ids if instance_id not in positions
    ]
    if missing:
        raise ValueError(f"instance IDs not found in input Parquet: {missing}")

    selected = dataset.select([positions[instance_id] for instance_id in instance_ids])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    selected.to_parquet(str(args.output))

    print(
        f"Wrote {len(selected)} selected instances to {args.output.resolve()}",
        flush=True,
    )
    for row in selected:
        task = row["extra_info"]["tools_kwargs"]["task"]
        print(
            f"  {task['metadata']['instance_id']}: {task['sandbox']['image']}",
            flush=True,
        )


if __name__ == "__main__":
    main()
